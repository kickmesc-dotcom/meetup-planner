/**
 * Объявление результата для скринридера.
 *
 * Зачем. После поиска, смены фильтра или «показать ещё» человек видит новый
 * список, а скринридер молчит: содержимое поменялось без действия, о котором
 * он бы сообщил. NVDA и VoiceOver в такой момент не читают ни числа, ни факт
 * «ничего не найдено» — и человек не понимает, сработал ли фильтр.
 *
 * Почему отдельный компонент, а не `aria-live` на самом списке. Живой регион
 * на контейнере читал бы каждую добавленную строку — это превращается в поток
 * текста, который нельзя прервать. Здесь объявляется короткий итог, а сам
 * список остаётся обычным: его человек изучает стрелками.
 *
 * `aria-atomic` — чтобы читалось всё сообщение целиком, а не только
 * изменившийся фрагмент: «Показано 20» без «из 140» бесполезно.
 */
export default function StatusAnnouncer({ text }: { text: string }) {
  return (
    <p role="status" aria-live="polite" aria-atomic="true" className="sr-only">
      {text}
    </p>
  );
}
