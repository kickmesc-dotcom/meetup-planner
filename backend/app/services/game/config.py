def points_for(code: str) -> int:
    """Опыт за событие. Неизвестный код → 0 (не падаем на новых событиях)."""
    rule = XP_RULES.get(code)
    return rule.points if rule else 0


def limit_for(code: str) -> Limit:
    rule = XP_RULES.get(code)
    return rule.limit if rule else None


