def next_unlock_level(from_level: int) -> int | None:
    """Первый уровень ВЫШЕ указанного, который что-то открывает.

    Нужен для подсказок «что будет дальше» (главная ценность — сказать игроку
    ровно один следующий шаг, а не весь список разблокировок).
    """
