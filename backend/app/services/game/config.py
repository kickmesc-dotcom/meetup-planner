    points: int
    title: str
    limit: Limit = None
    # Цена не фиксирована, а назначается вызывающим кодом: «случайное событие»
    # платит столько, сколько обещал конкретный призыв, а «контрабанда» —
    # столько, сколько записано за словом в реестре. Нужно только для текстов:
    # без этого флага подсказка честно показывала бы «+0 XP».
    variable: bool = False


