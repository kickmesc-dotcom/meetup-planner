# Как называть «окно идемпотентности» начисления: защита от абьюза и дублей.
#   None     — без ограничений (можно сколько угодно раз)
#   "day"    — один раз в UTC-сутки
#   "week"   — один раз в ISO-неделю
#   "year"   — один раз в календарный год
#   "once"   — один раз за всё время
Limit = str | None


@dataclass(frozen=True)
class XpRule:
    """Правило начисления опыта за событие.

    `code` — стабильный ключ события (пишется в `xp_events.event`), его менять
    нельзя даже при переименовании текста: по нему считается статистика.
    """

    code: str
    points: int
    title: str
    limit: Limit = None
    # Цена не фиксирована, а назначается вызывающим кодом: «случайное событие»
    # платит столько, сколько обещал конкретный призыв, а «контрабанда» —
    # столько, сколько записано за словом в реестре. Нужно только для текстов:
    # без этого флага подсказка честно показывала бы «+0 XP».
    variable: bool = False


XP_RULES: dict[str, XpRule] = {
    r.code: r
    for r in (
        XpRule("message", 1, "Сообщение в чате"),
        XpRule("quote", 1, "Бот процитировал твоё сообщение"),
        # Лимиты у этих двух нужны не для ограничения частоты, а для
        # идемпотентности КОНКРЕТНОГО случая: дискриминатор — id ролла / недели,
        # поэтому ретрай доставки не начислит второй раз за того же лоха/чухана.
        XpRule("became_loser", 10, "Стал лохом дня", limit="day"),
        XpRule("became_chukhan", 100, "Стал чуханом недели", limit="week"),
        XpRule("achievement", 50, "Получил ачивку"),
        # По заданию: «опыт даётся только раз в неделю, защита от абьюза».
        XpRule(
            "availability",
            10,
            "Разметил свободные дни",
            limit="week",
        ),
        XpRule("birthday", 100, "День рождения", limit="year"),
        XpRule("holiday", 50, "Праздник", limit="year"),
        XpRule("meeting", 50, "Инициировал встречу", limit="day"),
        XpRule("donation_sent", 0, "Подарил опыт имениннику", limit="once"),
        XpRule("donation_received", 100, "Получил опыт в подарок", limit="year"),
        # Случайное событие: сколько именно — решает промпт
        # (`events_catalog.py`), поэтому здесь 0 и вызов идёт с `points=`.
        XpRule("event", 0, "Случайное событие в чате", limit="day", variable=True),
        # Контрабанда: начисляется ВЛАДЕЛЬЦУ слова, а не тому, кто его написал.
        # Сколько — задаётся в реестре слов, поэтому здесь 0.
        XpRule(
            "contraband",
            0,
            "Кодовое слово сработало (опыт — владельцу слова)",
            limit="day",
            variable=True,
        ),
    )
}

