"""Человекочитаемая история изменений (для чат-команды `/changelog`).

Здесь лежит редакторская версия коммитов: каждое изменение переписано так,
чтобы его понял человек, который не читал код и не знает слов «рефакторинг»,
«миграция» и «эндпоинт». Это не перевод ради перевода — рядом с фактом стоит
пояснение, как оно работает в жизни.

Правило продукта (раунд 5): бот НИКОГДА не цитирует технический коммит как
есть. Сначала коммит проходит адаптацию — либо этой записью (её пишет человек
в момент релиза), либо автоматической расшифровкой в `services/changelog.py`.
Если ни то, ни другое не дало читаемой строки, изменение попадает в блок
«внутренние улучшения» без технического текста.

Как добавить запись после релиза:

1. `git log --oneline` — берём хеши того, что уехало;
2. дописываем `Entry` в начало `ENTRIES` с датой, коротким заголовком,
   объяснением «как это работает» и списком хешей, которые она покрывает;
3. всё, что не покрыто, бот доскажет сам — но уже человеческими словами.

Хеши сверяются по префиксу (7 символов достаточно), поэтому дописывать полный
SHA не нужно.
"""

