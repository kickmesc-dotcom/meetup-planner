def curated_for(sha: str) -> Entry | None:
    """Запись, которая уже объяснила этот коммит человеческим языком."""
    short = sha[:7]
    for entry in ENTRIES:
        for known in entry.commits:
            if short.startswith(known[:7]) or known[:7].startswith(short):
                return entry
    return None


def covered_shas() -> set[str]:
    """Короткие хеши, которые уже покрыты редакторскими записями."""
    return {sha[:7] for entry in ENTRIES for sha in entry.commits}
